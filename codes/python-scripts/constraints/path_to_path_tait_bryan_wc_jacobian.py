import sympy
from sympy import *
import sys
sys.path.insert(1, '..')
from tait_bryan_R_utils import *

# Fitting two paths (trajectories) of instruments carried on one rig, e.g. a lidar (reference) and a camera.
# For every instrument pose m measured at time t:
#     W * S(m) = R(t + dt) * O
# R(t + dt) - reference pose interpolated at t (tx_r..ka_r), moved by the time offset dt along its rate of change
#             (vtx_r..vka_r, time derivatives of the Tait-Bryan parameters); dt is the correction to the time offset
#             the reference pose was interpolated at
# O         - instrument offset: instrument pose in the reference body frame (tx_o..ka_o)
# W         - frame of the instrument path in the reference world (tx_w..ka_w)
# S(m)      - measured instrument pose (tx_m..ka_m) with its translation scaled by s (scale offset of the instrument path)
# residual: relative pose (W * S(m))^-1 * R(t + dt) * O, target identity

tx_r, ty_r, tz_r = symbols('tx_r ty_r tz_r')
om_r, fi_r, ka_r = symbols('om_r fi_r ka_r')
vtx_r, vty_r, vtz_r = symbols('vtx_r vty_r vtz_r')
vom_r, vfi_r, vka_r = symbols('vom_r vfi_r vka_r')
tx_o, ty_o, tz_o = symbols('tx_o ty_o tz_o')
om_o, fi_o, ka_o = symbols('om_o fi_o ka_o')
tx_w, ty_w, tz_w = symbols('tx_w ty_w tz_w')
om_w, fi_w, ka_w = symbols('om_w fi_w ka_w')
dt, s = symbols('dt s')
tx_m, ty_m, tz_m = symbols('tx_m ty_m tz_m')
om_m, fi_m, ka_m = symbols('om_m fi_m ka_m')

offset_symbols = [tx_o, ty_o, tz_o, om_o, fi_o, ka_o]
frame_symbols = [tx_w, ty_w, tz_w, om_w, fi_w, ka_w]
all_symbols = offset_symbols + frame_symbols + [dt, s]

Rt_r = matrix44FromTaitBryan(tx_r + dt * vtx_r, ty_r + dt * vty_r, tz_r + dt * vtz_r, om_r + dt * vom_r, fi_r + dt * vfi_r, ka_r + dt * vka_r)
Rt_o = matrix44FromTaitBryan(tx_o, ty_o, tz_o, om_o, fi_o, ka_o)
Rt_w = matrix44FromTaitBryan(tx_w, ty_w, tz_w, om_w, fi_w, ka_w)
Rt_m = matrix44FromTaitBryan(s * tx_m, s * ty_m, s * tz_m, om_m, fi_m, ka_m)

Rt_observed = Rt_w * Rt_m
R_observed_inv = Rt_observed[:-1, :-1].transpose()
t_observed_inv = -R_observed_inv * Rt_observed[:-1, 3]
Rt_observed_inv = Matrix.vstack(Matrix.hstack(R_observed_inv, t_observed_inv), Matrix([[0, 0, 0, 1]]))

relative_pose = Rt_observed_inv * Rt_r * Rt_o

parametrization = taitBryanFromMatrix44Case1(relative_pose)
t = relative_pose[0:3, 3]

target_value = Matrix([0, 0, 0, 0, 0, 0])
model_function = t.col_join(parametrization)
delta = target_value - model_function
delta_jacobian = delta.jacobian(all_symbols)

print("cse")
variables, simple = sympy.cse([delta, delta_jacobian], order='none', symbols=symbols('a0:100000'))
delta_simple = simple[0]
delta_jacobian_simple = simple[1]

arguments = ("double tx_r, double ty_r, double tz_r, double om_r, double fi_r, double ka_r, "
             "double vtx_r, double vty_r, double vtz_r, double vom_r, double vfi_r, double vka_r, "
             "double tx_o, double ty_o, double tz_o, double om_o, double fi_o, double ka_o, "
             "double tx_w, double ty_w, double tz_w, double om_w, double fi_w, double ka_w, "
             "double dt, double s, "
             "double tx_m, double ty_m, double tz_m, double om_m, double fi_m, double ka_m")

with open("path_to_path_tait_bryan_wc_jacobian.h", 'w') as f_cpp:
    f_cpp.write("#ifndef _PATH_TO_PATH_TAIT_BRYAN_WC_JACOBIAN_H_\n")
    f_cpp.write("#define _PATH_TO_PATH_TAIT_BRYAN_WC_JACOBIAN_H_\n")
    f_cpp.write("// generated by path_to_path_tait_bryan_wc_jacobian.py\n")
    f_cpp.write("// observation: W * S(m) = R(t + dt) * O; delta = 0 - [t, om, fi, ka] of (W * S(m))^-1 * R(t + dt) * O\n")
    f_cpp.write("// jacobian columns: tx_o ty_o tz_o om_o fi_o ka_o, tx_w ty_w tz_w om_w fi_w ka_w, dt, s\n")
    f_cpp.write("inline void path_to_path_obs_eq_tait_bryan_wc(Eigen::Matrix<double, 6, 1> &delta, %s)\n" % arguments)
    f_cpp.write("{\n")
    for name, value_expr in variables:
        f_cpp.write("double %s = %s;\n" % (name, ccode(value_expr)))
    for i in range(6):
        f_cpp.write("delta.coeffRef(%d,%d) = %s;\n" % (i, 0, ccode(delta_simple[i])))
    f_cpp.write("}\n")
    f_cpp.write("\n")
    f_cpp.write("inline void path_to_path_obs_eq_tait_bryan_wc_jacobian(Eigen::Matrix<double, 6, 14, Eigen::RowMajor> &j, %s)\n" % arguments)
    f_cpp.write("{\n")
    for name, value_expr in variables:
        f_cpp.write("double %s = %s;\n" % (name, ccode(value_expr)))
    for i in range(6):
        for k in range(14):
            f_cpp.write("j.coeffRef(%d,%d) = %s;\n" % (i, k, ccode(delta_jacobian_simple[i, k])))
    f_cpp.write("}\n")
    f_cpp.write("#endif\n")
